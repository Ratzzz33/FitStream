// Storage key for language preference
const LANGUAGE_KEY = 'fitstream_language';

// Get browser language
const getBrowserLanguage = (): Language => {
    const lang = navigator.language.split('-')[0];
    if (['en', 'ru', 'es', 'fr', 'de', 'zh', 'ka'].includes(lang)) {
        return lang as Language;
    }
    return 'en';
};

// Get current language (from settings or browser)
export const getLanguage = (): Language => {
    try {
        const stored = localStorage.getItem(LANGUAGE_KEY);
        if (stored && stored !== 'auto' && ['en', 'ru', 'es', 'fr', 'de', 'zh', 'ka'].includes(stored)) {
            return stored as Language;
        }
    } catch {
        // localStorage not available
    }
    return getBrowserLanguage();
};

// Set language preference
export const setLanguage = (lang: 'auto' | Language): void => {
    try {
        if (lang === 'auto') {
            localStorage.removeItem(LANGUAGE_KEY);
        } else {
            localStorage.setItem(LANGUAGE_KEY, lang);
        }
    } catch {
        // localStorage not available
    }
};

// Get saved language preference (for UI)
export const getSavedLanguage = (): 'auto' | Language => {
    try {
        const stored = localStorage.getItem(LANGUAGE_KEY);
        if (stored && ['en', 'ru', 'es', 'fr', 'de', 'zh', 'ka'].includes(stored)) {
            return stored as Language;
        }
    } catch {
        // localStorage not available
    }
    return 'auto';
};

